
import React, { useEffect, useState } from "react";

import {
    UsersRound,
    ShoppingCart,
    BrainCircuit,
    GitCompareArrows
} from "lucide-react";

import Sidebar from "../components/Sidebar";
import Header from "../components/Header";
import StatCard from "../components/StatCard";
import ModuleCard from "../components/ModuleCard";

import PurchasePrediction from "./PurchasePrediction";
import MarketBasketAnalysis from "./MarketBasketAnalysis";

import "../styles/Dashboard.css";
import "../styles/ModulePages.css";

function Dashboard() {
    const [backendStatus, setBackendStatus] = useState("Checking...");
    const [activeModule, setActiveModule] = useState(null);

    useEffect(() => {
        const controller = new AbortController();

        fetch("http://127.0.0.1:5000/api/health", {
            signal: controller.signal
        })
            .then((response) => {
                if (!response.ok) {
                    throw new Error("Backend request failed");
                }

                return response.json();
            })
            .then((data) => {
                setBackendStatus(
                    data.status === "success"
                        ? "Connected"
                        : "Disconnected"
                );
            })
            .catch((error) => {
                if (error.name !== "AbortError") {
                    setBackendStatus("Disconnected");
                }
            });

        return () => controller.abort();
    }, []);

    const stats = [
        {
            title: "Total Customers",
            value: "—",
            description: "Customer records in dataset",
            icon: UsersRound
        },
        {
            title: "Total Transactions",
            value: "—",
            description: "Recorded purchase transactions",
            icon: ShoppingCart
        },
        {
            title: "Purchase Predictions",
            value: "—",
            description: "Predictions generated by the model",
            icon: BrainCircuit
        },
        {
            title: "Product Associations",
            value: "—",
            description: "Associations discovered using Apriori",
            icon: GitCompareArrows
        }
    ];

    const modules = [
        {
            id: "purchase-prediction",
            number: "01",
            title: "Purchase Prediction",
            description:
                "Estimate whether a customer is likely to make a purchase using historical customer and transaction data.",
            algorithm: "Machine Learning"
        },
        {
            id: "market-basket",
            number: "02",
            title: "Market Basket Analysis",
            description:
                "Discover products frequently purchased together and identify useful product associations.",
            algorithm: "Apriori Algorithm"
        }
    ];

    function renderActivePage() {
        if (activeModule === "purchase-prediction") {
            return (
                <PurchasePrediction
                    onBack={() => setActiveModule(null)}
                />
            );
        }

        if (activeModule === "market-basket") {
            return (
                <MarketBasketAnalysis
                    onBack={() => setActiveModule(null)}
                />
            );
        }

        return (
            <>
                <section className="dashboard-welcome">
                    <div>
                        <p className="welcome-label">
                            CUSTOMER INSIGHTS PLATFORM
                        </p>

                        <h2>Welcome to Smart Purchase Analytics</h2>

                        <p>
                            Turn purchase data into insights to understand
                            customers and discover product trends.
                        </p>
                    </div>

                    <div className="welcome-decoration">SPA</div>
                </section>

                <section className="stats-section">
                    <h2 className="section-heading">
                        Analytics Overview
                    </h2>

                    <div className="stats-grid">
                        {stats.map((stat) => (
                            <StatCard
                                key={stat.title}
                                title={stat.title}
                                value={stat.value}
                                description={stat.description}
                                icon={stat.icon}
                            />
                        ))}
                    </div>
                </section>

                <section className="modules-section">
                    <div className="modules-heading">
                        <div>
                            <h2 className="section-heading">
                                Project Modules
                            </h2>

                            <p className="modules-subtitle">
                                Explore the two main analytical features.
                            </p>
                        </div>
                    </div>

                    <div className="modules-grid">
                        {modules.map((module) => (
                            <ModuleCard
                                key={module.id}
                                {...module}
                                onClick={() =>
                                    setActiveModule(module.id)
                                }
                            />
                        ))}
                    </div>
                </section>

                <footer className="dashboard-footer">
                    Smart Purchase Analytics · Machine Learning + Apriori
                </footer>
            </>
        );
    }

    return (
        <div className="app-layout" id="dashboard">
            <Sidebar
                activeModule={activeModule}
                onNavigate={setActiveModule}
            />

            <main className="main-content">
                <Header backendStatus={backendStatus} />

                {renderActivePage()}
            </main>
        </div>
    );
}

export default Dashboard;
